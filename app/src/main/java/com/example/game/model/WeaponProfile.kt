    val isHistoricalCollectible: Boolean
        get() = !isMelee && era != WeaponEra.MODERN

    val rpmDisplay: Int
        get() = if (fireDelayMs <= 0L) 0 else (60_000L / fireDelayMs).toInt()

    companion object {
        fun fromKey(key: String): WeaponId = entries.firstOrNull { it.key == key } ?: KNIFE
        val historicalCollectibles: List<WeaponId> by lazy { entries.filter { it.isHistoricalCollectible } }
        fun collectiblesForEra(era: WeaponEra): List<WeaponId> = entries.filter { it.isHistoricalCollectible && it.era == era }
    }
